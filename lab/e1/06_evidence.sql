declare
  c_expected constant pls_integer := 19;
  c_ts_fmt   constant varchar2(30) := 'YYYY-MM-DD HH24:MI:SS';
  -- Password generated by the runner: E1 + 22 alphanumerics, isolated by a boundary
  c_pwd_re   constant varchar2(80) := '(^|[^A-Za-z0-9])E1[A-Za-z0-9]{22}([^A-Za-z0-9]|$)';
  v_pass     pls_integer := 0;
  v_fail     pls_integer := 0;
  v_start    varchar2(30)  := :g_start;
  v_start_db varchar2(30)  := :g_start_db;
  v_base     varchar2(10)  := :g_base;
  v_dg_base  varchar2(10)  := :g_dg_base;
  v_dr_base  varchar2(10)  := :g_dr_base;
  v_apex     varchar2(100) := :g_apex;
  v_txt      varchar2(4000);

  procedure p_check(p_id in varchar2, p_desc in varchar2,
                    p_expected in varchar2, p_actual in varchar2) is
  begin
    if p_actual is not null and p_actual = p_expected then
      v_pass := v_pass + 1;
      dbms_output.put_line('PASS ' || p_id || ' | ' || p_desc
                           || ' | expected=' || p_expected || ' | actual=' || p_actual);
    else
      v_fail := v_fail + 1;
      dbms_output.put_line('FAIL ' || p_id || ' | ' || p_desc
                           || ' | expected=' || p_expected || ' | actual=' || nvl(p_actual, '<NULL>'));
    end if;
  end p_check;

  -- Observation of an open item: prints, does not count
  procedure p_obs(p_id in varchar2, p_desc in varchar2, p_actual in varchar2) is
  begin
    dbms_output.put_line('OBS  ' || p_id || ' | ' || p_desc || ' | actual=' || nvl(p_actual, '<NULL>'));
  end p_obs;

  -- Dynamic scalar query with up to 2 binds; returns the value or ORA-NNNNN
  function f_query(p_sql in varchar2, p_b1 in varchar2 default null,
                   p_b2 in varchar2 default null) return varchar2 is
    v_val  varchar2(4000);
    v_code number;
  begin
    if p_b2 is not null then
      execute immediate p_sql into v_val using p_b1, p_b2;
    elsif p_b1 is not null then
      execute immediate p_sql into v_val using p_b1;
    else
      execute immediate p_sql into v_val;
    end if;
    return v_val;
  exception
    when others then
      v_code := sqlcode;
      dbms_output.put_line('INFO      error caught in query: ' || substr(sqlerrm, 1, 200));
      return 'ORA-' || to_char(abs(v_code), 'FM00000');
  end f_query;

begin
  -- ---------- Configuration in the dictionary ----------
  p_check('E01', 'lab end users with OPEN account', '4', f_query(
    q'[select to_char(count(*)) from dba_end_users
        where username in ('DDS_EU_NORTH','DDS_EU_SOUTH','DDS_EU_NOACCESS','DDS_EU_NOROLE')
          and account_status = 'OPEN']'));
  p_check('E02', 'lab data roles', '3', f_query(
    q'[select to_char(count(*)) from dba_data_roles
        where data_role in ('DDS_DR_NORTH','DDS_DR_SOUTH','DDS_DR_SESSION_ONLY')]'));
  p_check('E03', 'data role per end user (NOROLE has none)',
          'DDS_EU_NOACCESS>DDS_DR_SESSION_ONLY,DDS_EU_NORTH>DDS_DR_NORTH,DDS_EU_SOUTH>DDS_DR_SOUTH',
          f_query(q'[select listagg(grantee || '>' || data_role, ',')
                              within group (order by grantee, data_role)
                       from dba_data_role_grants
                      where substr(grantee, 1, 7) = 'DDS_EU_']'));
  p_check('E04', 'database role DDS_SESSION_ROLE on the 3 data roles',
          'DDS_DR_NORTH,DDS_DR_SESSION_ONLY,DDS_DR_SOUTH',
          f_query(q'[select listagg(grantee, ',') within group (order by grantee)
                       from dba_data_role_grants
                      where data_role = 'DDS_SESSION_ROLE' and role_type = 'DATABASE ROLE']'));
  p_check('E05', 'lab data grants',
          'INV_NORTH_OWN_STATUS_UPD,INV_NORTH_READ,INV_SOUTH_READ',
          f_query(q'[select listagg(distinct grant_name, ',') within group (order by grant_name)
                       from dba_data_grants where owner = 'DDS_ADMIN']'));
  -- E06: end-user access comes only from data grants, never from a classic GRANT SELECT
  p_check('E06', 'no classic object privilege on DDS_INV_OWNER', '0', f_query(
    q'[select to_char(count(*)) from dba_tab_privs where owner = 'DDS_INV_OWNER']'));
  -- E07/E08: design A2. DDS_ADMIN only creates data grants: 2 system privileges,
  --          no role, and ADMINISTER ANY DATA GRANT restricted to the lab schema.
  --          Identities (end users, data roles) stayed with SYS in 04a.
  p_check('E07', 'DDS_ADMIN system privileges (exactly 2)',
          'CREATE DATA GRANT,CREATE SESSION',
          f_query(q'[select listagg(privilege, ',') within group (order by privilege)
                       from dba_sys_privs where grantee = 'DDS_ADMIN']'));
  p_check('E08', 'DDS_ADMIN roles and schema privilege',
          'ROLES=0;SCHEMA=ADMINISTER ANY DATA GRANT@DDS_INV_OWNER',
          'ROLES=' || f_query(q'[select to_char(count(*)) from dba_role_privs
                                  where grantee = 'DDS_ADMIN']')
          || ';SCHEMA=' || f_query(q'[select listagg(privilege || '@' || "SCHEMA", ',')
                                              within group (order by privilege, "SCHEMA")
                                       from dba_schema_privs where grantee = 'DDS_ADMIN']'));
  p_check('E09', 'DDS_INV_PARSE without any privilege', '0', f_query(
    q'[select to_char((select count(*) from dba_sys_privs    where grantee = 'DDS_INV_PARSE')
                    + (select count(*) from dba_role_privs   where grantee = 'DDS_INV_PARSE')
                    + (select count(*) from dba_tab_privs    where grantee = 'DDS_INV_PARSE')
                    + (select count(*) from dba_schema_privs where grantee = 'DDS_INV_PARSE'))
         from dual]'));

  -- ---------- Audit since the run start ----------
  -- E10: DDS_ADMIN runs exactly 3 CREATE DATA GRANT in 04b. Configuration does
  --      not fill END_USER_NAME (chapter 19). The SYS actions in 04a are in O06.
  p_check('E10', 'data grants audited as DDS_ADMIN', 'MIN3=OK;END_USER_NAME_FILLED=0', f_query(
    q'[select 'MIN3=' || case when count(*) >= 3 then 'OK' else to_char(count(*)) end
              || ';END_USER_NAME_FILLED=' || count(end_user_name)
         from unified_audit_trail
        where instr(unified_audit_policies, 'DDS_E1_CONFIG_POL') > 0
          and dbusername = 'DDS_ADMIN' and return_code = 0
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  -- E11: verified in the first E1 run (Free 23.26.3): the database also creates
  --      and audits, with RETURN_CODE 0, a security context for DDS_EU_NOROLE,
  --      whose logon is then refused with ORA-01045. A successful context record
  --      is therefore NOT proof of a successful logon. The original expectation
  --      (N, S and X only) was a documentation hypothesis and failed.
  p_check('E11', 'security context created and audited for all 4 (NOROLE included)',
          'DDS_EU_NOACCESS,DDS_EU_NOROLE,DDS_EU_NORTH,DDS_EU_SOUTH', f_query(
    q'[select listagg(distinct coalesce(end_user_name, dbusername), ',')
                within group (order by coalesce(end_user_name, dbusername))
         from unified_audit_trail
        where instr(unified_audit_policies, 'DDS_E1_CTX_POL') > 0
          and return_code = 0
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  -- E12: identity propagation down to the audit trail. The CONTEXT_ID column is
  --      only tested as NOT NULL; the value is never printed.
  p_check('E12', 'data access audited with END_USER_NAME and CONTEXT_ID',
          'DDS_EU_NORTH,DDS_EU_SOUTH', f_query(
    q'[select listagg(distinct end_user_name, ',') within group (order by end_user_name)
         from unified_audit_trail
        where instr(unified_audit_policies, 'DDS_E1_DATA_POL') > 0
          and end_user_name in ('DDS_EU_NORTH','DDS_EU_SOUTH')
          and end_user_security_context_id is not null
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  p_check('E13', 'denials audited with the end-user identity', 'NORTH=OK;SOUTH=OK', f_query(
    q'[select 'NORTH=' || case when count(case when end_user_name = 'DDS_EU_NORTH' then 1 end) > 0
                               then 'OK' else 'ZERO' end
              || ';SOUTH=' || case when count(case when end_user_name = 'DDS_EU_SOUTH' then 1 end) > 0
                                   then 'OK' else 'ZERO' end
         from unified_audit_trail
        where instr(unified_audit_policies, 'DDS_E1_DATA_POL') > 0
          and return_code <> 0
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  p_check('E14', 'authorized UPDATE attributed to DDS_EU_NORTH', 'OK', f_query(
    q'[select case when count(*) > 0 then 'OK' else 'ZERO' end
         from unified_audit_trail
        where instr(unified_audit_policies, 'DDS_E1_DATA_POL') > 0
          and action_name = 'UPDATE' and return_code = 0
          and end_user_name = 'DDS_EU_NORTH'
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  -- E15: no generated password (E1 + 22 alphanumerics, with a boundary) in the
  --      audited SQL_TEXT. The pattern goes as a bind; only the count is printed.
  p_check('E15', 'no generated password in the audited SQL_TEXT', '0', f_query(
    q'[select to_char(count(*)) from unified_audit_trail
        where regexp_like(sql_text, :b1)
          and event_timestamp_utc >= to_timestamp(:b2, 'YYYY-MM-DD HH24:MI:SS')]', c_pwd_re, v_start));

  -- ---------- Integrity and isolation ----------
  -- SYS reads the whole table through a classic privilege; this is NOT a bypass
  -- test (that belongs to E1-BP)
  p_check('E16', 'final table integrity (SYS view)', 'ROWS=12;SUM=76000;NOT_PENDING=0;TAX=12', f_query(
    q'[select 'ROWS=' || count(*) || ';SUM=' || sum(amount)
              || ';NOT_PENDING=' || sum(case when status <> 'PENDING' then 1 else 0 end)
              || ';TAX=' || count(supplier_tax_id)
         from dds_inv_owner.invoices]'));
  p_check('E17', 'INVALID objects equal to the 00 baseline', v_base, f_query(
    q'[select to_char(count(*)) from dba_objects where status = 'INVALID']'));
  -- E18: no user-schema object (ORACLE_MAINTAINED = N) outside the lab allowlist
  --      had DDL since the run start. A false positive is possible if another
  --      person or application runs DDL during the run (keep a quiet window).
  --      Verified in the first E1 run: every start of a repeating scheduler job
  --      sets the job's LAST_DDL_TIME to its LAST_START_DATE, so a JOB whose
  --      LAST_DDL_TIME matches its last start (2 s tolerance) is a run, not DDL.
  --      Limitation: real DDL on such a job before its latest run is masked.
  p_check('E18', 'no DDL in a schema outside the lab since the run start', '0', f_query(
    q'[select to_char(count(*)) from dba_objects o
        where o.owner in (select u.username from dba_users u where u.oracle_maintained = 'N')
          and o.owner not in ('DDS_INV_OWNER','DDS_ADMIN','DDS_INV_PARSE')
          and o.last_ddl_time >= to_date(:b1, 'YYYY-MM-DD HH24:MI:SS')
          and not exists (select 1 from dba_scheduler_jobs j
                           where o.object_type = 'JOB'
                             and j.owner = o.owner and j.job_name = o.object_name
                             and abs(o.last_ddl_time - cast(j.last_start_date as date)) <= 2 / 86400)]',
    v_start_db));
  -- E19: no user or end user created outside the allowlist; data grants and data
  --      roles that already existed outside the lab keep the count measured by 00
  p_check('E19', 'no new Deep Sec principal or user outside the lab',
          'NEW_USERS=0;NEW_END_USERS=0;DATA_GRANTS_OUTSIDE=' || v_dg_base
          || ';DATA_ROLES_OUTSIDE=' || v_dr_base, f_query(
    q'[select 'NEW_USERS=' || (select count(*) from dba_users
                                where created >= to_date(:b1, 'YYYY-MM-DD HH24:MI:SS')
                                  and username not in ('DDS_INV_OWNER','DDS_ADMIN','DDS_INV_PARSE',
                                                       'DDS_EU_NORTH','DDS_EU_SOUTH',
                                                       'DDS_EU_NOACCESS','DDS_EU_NOROLE'))
              || ';NEW_END_USERS=' || (select count(*) from dba_end_users
                                        where created_date >= to_date(:b2, 'YYYY-MM-DD HH24:MI:SS')
                                          and username not in ('DDS_EU_NORTH','DDS_EU_SOUTH',
                                                               'DDS_EU_NOACCESS','DDS_EU_NOROLE'))
              || ';DATA_GRANTS_OUTSIDE=' || (select count(*) from dba_data_grants
                                              where owner <> 'DDS_ADMIN')
              || ';DATA_ROLES_OUTSIDE=' || (select count(*) from dba_data_roles
                                             where data_role not in ('DDS_DR_NORTH','DDS_DR_SOUTH',
                                                                     'DDS_DR_SESSION_ONLY'))
         from dual]', v_start_db, v_start_db));

  -- ---------- Observations of open items (not counted) ----------
  p_obs('O01', 'CTX audited for DDS_EU_NOROLE', f_query(
    q'[select 'OK=' || count(case when return_code = 0 then 1 end)
              || ';FAILED=' || count(case when return_code <> 0 then 1 end)
         from unified_audit_trail
        where instr(unified_audit_policies, 'DDS_E1_CTX_POL') > 0
          and coalesce(end_user_name, dbusername) = 'DDS_EU_NOROLE'
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  -- O02: first E1 run returned NULL. The ORA-01045 refusal left no LOGON record
  --      (and no record with a non-zero return code at all) even with
  --      ORA_LOGIN_LOGOUT enabled for failures in the PDB.
  p_obs('O02', 'LOGON return codes for DDS_EU_NOROLE', f_query(
    q'[select listagg(distinct to_char(return_code), ',') within group (order by to_char(return_code))
         from unified_audit_trail
        where action_name = 'LOGON'
          and coalesce(end_user_name, dbusername) = 'DDS_EU_NOROLE'
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  p_obs('O03', 'DDS_EU_NOACCESS data records (RC=count)', f_query(
    q'[select listagg(rc || '=' || n, ',') within group (order by rc)
         from (select to_char(return_code) rc, count(*) n
                 from unified_audit_trail
                where instr(unified_audit_policies, 'DDS_E1_DATA_POL') > 0
                  and end_user_name = 'DDS_EU_NOACCESS'
                  and event_timestamp_utc >= to_timestamp(:b1, :b2)
                group by to_char(return_code))]', v_start, c_ts_fmt));
  p_obs('O04', 'DBUSERNAME recorded for end-user data access', f_query(
    q'[select listagg(distinct dbusername, ',') within group (order by dbusername)
         from unified_audit_trail
        where instr(unified_audit_policies, 'DDS_E1_DATA_POL') > 0
          and end_user_name is not null
          and event_timestamp_utc >= to_timestamp(:b1, :b2)]', v_start, c_ts_fmt));
  -- O05: [H] the shared pool may keep the text of CREATE ... IDENTIFIED BY.
  --      Only the count is printed. A value > 0 becomes a report finding, not a
  --      FAIL, because the cursor may have left the shared pool before 06.
  p_obs('O05', 'V$SQL cursors with the generated password pattern (count only)', f_query(
    q'[select to_char(count(*)) from v$sql where regexp_like(sql_fulltext, :b1)]', c_pwd_re));
  -- O06: [H] SYS configuration actions in 04a captured by DDS_E1_CONFIG_POL.
  --      Expected 10 = 3 CREATE DATA ROLE + 4 CREATE END USER + 3 GRANT DATA ROLE.
  p_obs('O06', 'SYS configuration actions audited (expected [H] TOTAL=10)', f_query(
    q'[select 'TOTAL=' || sum(n) || ';' || listagg(action_name || '=' || n, ',')
                                              within group (order by action_name)
         from (select action_name, count(*) n
                 from unified_audit_trail
                where instr(unified_audit_policies, 'DDS_E1_CONFIG_POL') > 0
                  and dbusername = 'SYS'
                  and event_timestamp_utc >= to_timestamp(:b1, :b2)
                group by action_name)]', v_start, c_ts_fmt));
  -- O07: APEX fingerprint (application count and last update), compared with the
  --      one from 00. Column LAST_UPDATED_ON is [H]; if it is missing, both sides
  --      are UNAVAILABLE and the comparison proves nothing (the report says so).
  begin
    execute immediate q'[select count(*) || ':'
                                || nvl(to_char(max(last_updated_on), 'YYYYMMDDHH24MISS'), '-')
                           from apex_applications]'
      into v_txt;
  exception
    when others then
      dbms_output.put_line('INFO      APEX fingerprint unavailable: ' || substr(sqlerrm, 1, 200));
      v_txt := 'UNAVAILABLE';
  end;
  p_obs('O07', 'APEX fingerprint (00 baseline vs now)',
        case when v_txt = 'UNAVAILABLE' or v_apex = 'UNAVAILABLE' then 'NO_PROOF'
             when v_txt = v_apex then 'MATCH'
             else 'DIFF' end
        || ';baseline=' || v_apex || ';now=' || v_txt);

  dbms_output.put_line('SUMMARY 06_evidence | pass=' || v_pass || ' | fail=' || v_fail
                       || ' | expected=' || c_expected);
  :g_rc := case when v_fail = 0 and v_pass = c_expected then 0 else 2 end;
end;
